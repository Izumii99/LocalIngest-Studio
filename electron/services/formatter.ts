import type { FileNode, OutputFormat } from '../../src/types/index.ts';

export interface FileItem {
  relativePath: string;
  content: string;
  size?: number;
}

export interface FormatOptions {
  format: OutputFormat;
  systemPrompt?: string;
  includeAsciiTree?: boolean;
  treeRoot?: FileNode;
  selectedPaths?: Set<string>;
  maxFileSizeKB?: number;
  redactSecrets?: boolean;
  dietMode?: boolean;
}

const SECRET_PATTERNS = [
  /\bsk-[a-zA-Z0-9_-]{24,}\b/g,
  /\bsk-ant-[a-zA-Z0-9_-]{24,}\b/g,
  /\b(ghp|gho|ghu|ghs|ghr)_[a-zA-Z0-9]{36}\b/g,
  /\bAKIA[0-9A-Z]{16}\b/g,
  /-----BEGIN (?:RSA |EC |DSA |OPENSSH )?PRIVATE KEY-----/g,
];

/**
 * Generates an ASCII tree structure representing selected files and folders.
 */
export function generateAsciiTree(
  node: FileNode,
  selectedPaths?: Set<string>,
  prefix = '',
  isLast = true
): string {
  // If selectedPaths is provided, skip nodes that have no selected descendants
  if (selectedPaths && !hasSelectedDescendant(node, selectedPaths)) {
    return '';
  }

  const marker = isLast ? '└── ' : '├── ';
  let line = prefix ? `${prefix}${marker}${node.name}` : node.name;
  if (node.isDirectory) {
    line += '/';
  }

  const lines = [line];

  if (node.isDirectory && node.children) {
    // Filter children to only those selected or having selected children
    const visibleChildren = selectedPaths
      ? node.children.filter((child) => hasSelectedDescendant(child, selectedPaths))
      : node.children;

    const nextPrefix = prefix ? `${prefix}${isLast ? '    ' : '│   '}` : '';

    visibleChildren.forEach((child, index) => {
      const childIsLast = index === visibleChildren.length - 1;
      const childTree = generateAsciiTree(child, selectedPaths, nextPrefix, childIsLast);
      if (childTree) {
        lines.push(childTree);
      }
    });
  }

  return lines.join('\n');
}

function hasSelectedDescendant(node: FileNode, selectedPaths: Set<string>): boolean {
  if (selectedPaths.has(node.relativePath)) {
    return true;
  }
  if (node.isDirectory && node.children) {
    return node.children.some((child) => hasSelectedDescendant(child, selectedPaths));
  }
  return false;
}

function processFileContent(file: FileItem, options: FormatOptions): string {
  // 1. Max file size check
  if (options.maxFileSizeKB && options.maxFileSizeKB > 0 && file.size) {
    const limitBytes = options.maxFileSizeKB * 1024;
    if (file.size > limitBytes) {
      return `[Content omitted: File size (${(file.size / 1024).toFixed(1)} KB) exceeds limit of ${options.maxFileSizeKB} KB]`;
    }
  }

  let content = file.content;

  // 2. Secret Redaction
  if (options.redactSecrets) {
    for (const pat of SECRET_PATTERNS) {
      pat.lastIndex = 0;
      content = content.replace(pat, '[REDACTED_SECRET]');
    }
  }

  // 3. Diet Mode: Prune heavy inline SVGs and large Base64 data URIs
  if (options.dietMode) {
    // Prune inline SVG bodies over 150 chars
    content = content.replace(/<svg\b([^>]*)>([\s\S]*?)<\/svg>/gi, (match, attrs, body) => {
      if (match.length <= 150) {
        return match;
      }
      const savedKB = (body.length / 1024).toFixed(1);
      return `<svg${attrs}><!-- [LocalIngest: SVG body omitted, ${savedKB} KB saved] --></svg>`;
    });

    // Prune large Base64 data URLs over 60 chars
    content = content.replace(
      /\bdata:(?:image|font|application)\/[a-zA-Z0-9.+-]+;base64,[A-Za-z0-9+/=\s]{60,}/g,
      (match) => {
        const semiIdx = match.indexOf(';base64,');
        const prefix = match.slice(0, semiIdx + 8);
        const savedKB = ((match.length - prefix.length) / 1024).toFixed(1);
        return `${prefix}[OMITTED_BY_LOCALINGEST_${savedKB}KB]`;
      }
    );
  }

  return content;
}

/**
 * Builds the output string according to the requested format (XML, Markdown, or Plain).
 */
export function formatOutput(
  files: FileItem[],
  options: FormatOptions
): string {
  const { format, systemPrompt, includeAsciiTree, treeRoot, selectedPaths } = options;

  let asciiTree = '';
  if (includeAsciiTree && treeRoot) {
    asciiTree = generateAsciiTree(treeRoot, selectedPaths);
  }

  // Pre-process contents (size limit & secret redaction)
  const processedFiles: FileItem[] = files.map((f) => ({
    ...f,
    content: processFileContent(f, options),
  }));

  switch (format) {
    case 'xml':
      return buildXmlFormat(processedFiles, systemPrompt, asciiTree);
    case 'markdown':
      return buildMarkdownFormat(processedFiles, systemPrompt, asciiTree);
    case 'plain':
    default:
      return buildPlainFormat(processedFiles, systemPrompt, asciiTree);
  }
}

function buildXmlFormat(files: FileItem[], prompt?: string, tree?: string): string {
  const parts: string[] = ['This file is a merged representation of the codebase, generated by LocalIngest Studio.\n'];

  if (prompt?.trim()) {
    parts.push(`<instructions>\n${prompt.trim()}\n</instructions>\n`);
  }

  if (tree) {
    parts.push(`<directory_structure>\n${tree}\n</directory_structure>\n`);
  }

  parts.push('<files>');
  for (const file of files) {
    parts.push(`  <file path="${file.relativePath}">\n${file.content}\n  </file>`);
  }
  parts.push('</files>');

  return parts.join('\n');
}

function buildMarkdownFormat(files: FileItem[], prompt?: string, tree?: string): string {
  const parts: string[] = ['# Project Codebase Context\n'];

  if (prompt?.trim()) {
    parts.push(`## Instructions\n${prompt.trim()}\n`);
  }

  if (tree) {
    parts.push(`## Directory Structure\n\`\`\`text\n${tree}\n\`\`\`\n`);
  }

  parts.push('## Files Content\n');
  for (const file of files) {
    const ext = file.relativePath.split('.').pop() || '';
    parts.push(`### \`${file.relativePath}\`\n\`\`\`${ext}\n${file.content}\n\`\`\`\n`);
  }

  return parts.join('\n');
}

function buildPlainFormat(files: FileItem[], prompt?: string, tree?: string): string {
  const parts: string[] = [];

  if (prompt?.trim()) {
    parts.push(`INSTRUCTIONS:\n${prompt.trim()}\n`);
    parts.push('='.repeat(50) + '\n');
  }

  if (tree) {
    parts.push('DIRECTORY STRUCTURE:');
    parts.push('='.repeat(50));
    parts.push(tree);
    parts.push('='.repeat(50) + '\n');
  }

  for (const file of files) {
    parts.push(`================================================`);
    parts.push(`File: ${file.relativePath}`);
    parts.push(`================================================`);
    parts.push(file.content);
    parts.push('\n');
  }

  return parts.join('\n');
}

export interface SplitPart {
  partIndex: number;
  totalParts: number;
  fileName: string;
  content: string;
  fileCount: number;
  estimatedBytes: number;
}

/**
 * Splits codebase files into connected multi-part bundles with manifest metadata
 * to stay safely within browser / web chat payload limits (< 450 KB per part).
 */
export function splitOutputIntoParts(
  files: FileItem[],
  options: FormatOptions,
  projectName = 'codebase',
  maxPartBytes = 450 * 1024
): SplitPart[] {
  const { format, systemPrompt, includeAsciiTree, treeRoot, selectedPaths } = options;

  let asciiTree = '';
  if (includeAsciiTree && treeRoot) {
    asciiTree = generateAsciiTree(treeRoot, selectedPaths);
  }

  const processedFiles: FileItem[] = files.map((f) => ({
    ...f,
    content: processFileContent(f, options),
  }));

  if (processedFiles.length === 0) {
    return [];
  }

  const encoder = new TextEncoder();
  const chunks: FileItem[][] = [];
  let currentChunk: FileItem[] = [];
  let currentChunkBytes = 0;

  for (const file of processedFiles) {
    const fileBytes = encoder.encode(file.content).length;
    if (currentChunk.length > 0 && currentChunkBytes + fileBytes > maxPartBytes) {
      chunks.push(currentChunk);
      currentChunk = [file];
      currentChunkBytes = fileBytes;
    } else {
      currentChunk.push(file);
      currentChunkBytes += fileBytes;
    }
  }

  if (currentChunk.length > 0) {
    chunks.push(currentChunk);
  }

  const totalParts = chunks.length;
  const ext = format === 'xml' ? 'xml' : format === 'markdown' ? 'md' : 'txt';

  return chunks.map((chunk, idx) => {
    const partIndex = idx + 1;
    const fileName = `${projectName}-part${partIndex}.${ext}`;
    const prevPartName = idx > 0 ? `${projectName}-part${idx}.${ext}` : 'none';
    const nextPartName = idx < totalParts - 1 ? `${projectName}-part${idx + 2}.${ext}` : 'none';

    let content = '';
    switch (format) {
      case 'xml': {
        const parts: string[] = [
          `This file is a merged representation of the codebase, generated by LocalIngest Studio (Split Part ${partIndex} of ${totalParts}).\n`,
          `<ingest_metadata>\n  <part current="${partIndex}" total="${totalParts}" />\n  <continuation_of>${prevPartName}</continuation_of>\n  <next_part>${nextPartName}</next_part>\n  <files_in_part>${chunk.length}</files_in_part>\n  <total_files_across_parts>${processedFiles.length}</total_files_across_parts>\n</ingest_metadata>\n`,
        ];

        if (systemPrompt?.trim()) {
          parts.push(`<instructions>\n${systemPrompt.trim()}\n</instructions>\n`);
        }

        if (asciiTree) {
          parts.push(`<directory_structure>\n${asciiTree}\n</directory_structure>\n`);
        }

        parts.push('<files>');
        for (const file of chunk) {
          parts.push(`  <file path="${file.relativePath}">\n${file.content}\n  </file>`);
        }
        parts.push('</files>');
        content = parts.join('\n');
        break;
      }
      case 'markdown': {
        const parts: string[] = [
          `# Project Codebase Context (Part ${partIndex} of ${totalParts})\n`,
          `> **Manifest**: Part ${partIndex} of ${totalParts} | Previous: \`${prevPartName}\` | Next: \`${nextPartName}\` | Files in this part: ${chunk.length} / ${processedFiles.length}\n`,
        ];

        if (systemPrompt?.trim()) {
          parts.push(`## Instructions\n${systemPrompt.trim()}\n`);
        }

        if (asciiTree) {
          parts.push(`## Directory Structure\n\`\`\`text\n${asciiTree}\n\`\`\`\n`);
        }

        parts.push('## Files Content\n');
        for (const file of chunk) {
          const fileExt = file.relativePath.split('.').pop() || '';
          parts.push(`### \`${file.relativePath}\`\n\`\`\`${fileExt}\n${file.content}\n\`\`\`\n`);
        }
        content = parts.join('\n');
        break;
      }
      case 'plain':
      default: {
        const parts: string[] = [
          `==================================================\nSPLIT PART ${partIndex} OF ${totalParts}\nContinuation of: ${prevPartName}\nNext part: ${nextPartName}\nFiles in part: ${chunk.length} / ${processedFiles.length}\n==================================================\n`,
        ];

        if (systemPrompt?.trim()) {
          parts.push(`INSTRUCTIONS:\n${systemPrompt.trim()}\n==================================================\n`);
        }

        if (asciiTree) {
          parts.push(`DIRECTORY STRUCTURE:\n${asciiTree}\n==================================================\n`);
        }

        for (const file of chunk) {
          parts.push(`================================================\nFile: ${file.relativePath}\n================================================\n${file.content}\n`);
        }
        content = parts.join('\n');
        break;
      }
    }

    return {
      partIndex,
      totalParts,
      fileName,
      content,
      fileCount: chunk.length,
      estimatedBytes: encoder.encode(content).length,
    };
  });
}
